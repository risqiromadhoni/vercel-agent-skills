// Shared helpers for the skill-bench scripts. Dependency-free apart from tsx,
// which loads the TypeScript rule parser. Node >= 20.
import { createHash } from 'node:crypto'
import { access, readdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseRuleFile } from '../../../react-best-practices-build/src/parser.ts'

export const FIXTURES = ['nextjs', 'tanstack-start']
export const SKILLS = ['react-best-practices', 'composition-patterns']

export const BENCH_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..')
const REPO_ROOT = resolve(BENCH_DIR, '..', '..')

export const log = (msg) => process.stderr.write(`${msg}\n`)

export const fixtureDir = (fw) => join(BENCH_DIR, 'fixtures', fw)
export const stubPath = (fw, id) => join(fixtureDir(fw), 'src', 'rules', `${id}.tsx`)
export const rulesIndexPath = (fw) => join(fixtureDir(fw), 'src', 'rules', 'index.ts')
const skillRulesDir = (skill) => join(REPO_ROOT, 'skills', skill, 'rules')

export async function exists(path) {
  try {
    await access(path)
    return true
  } catch {
    return false
  }
}

/** Rule IDs for a skill: file basenames without .md, skipping _*.md helpers. */
export async function listRuleIds(skill) {
  const files = await readdir(skillRulesDir(skill))
  return files
    .filter((f) => f.endsWith('.md') && !f.startsWith('_'))
    .map((f) => f.slice(0, -'.md'.length))
    .sort()
}

/** Rule-to-framework mapping: { "<rule-id>": { nextjs, "tanstack-start", note, pending? } } */
export async function readMapping(skill) {
  return JSON.parse(await readFile(join(BENCH_DIR, 'mapping', `${skill}.json`), 'utf8'))
}

/** Status for a rule on a framework: 'port' | 'equivalent' | 'na' | null when unmapped. */
export function frameworkStatus(mapping, id, fw) {
  return mapping[id]?.[fw] ?? null
}

// Whole-word match so that "Incorrect (...)" never counts as "Correct".
const CORRECT_LABEL = /\bcorrect\b/i

/** First example whose label says "Correct", or null. */
export function pickCorrectExample(rule) {
  return rule.examples.find((ex) => CORRECT_LABEL.test(ex.label)) ?? null
}

export function hashCode(code) {
  return createHash('sha256').update(code).digest('hex')
}

/** Parses skills/<skill>/rules/<id>.md and returns { code, hash } for its Correct example, or null. */
export async function correctExample(skill, id) {
  const { rule } = await parseRuleFile(join(skillRulesDir(skill), `${id}.md`))
  const example = pickCorrectExample(rule)
  if (!example) return null
  return { code: example.code, hash: hashCode(example.code) }
}

export function stubSource(skill, id, hash, code) {
  return [
    `// SOURCE: skills/${skill}/rules/${id}.md`,
    `// HASH: ${hash}`,
    code,
    '',
  ].join('\n')
}

export async function readManifest(fw) {
  try {
    return JSON.parse(await readFile(join(fixtureDir(fw), 'rules.manifest.json'), 'utf8'))
  } catch (err) {
    if (err.code === 'ENOENT') return {}
    throw err
  }
}

/** Writes the manifest with keys sorted so diffs stay small. */
export async function writeManifest(fw, manifest) {
  const sorted = Object.fromEntries(
    Object.entries(manifest).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
  )
  await writeFile(join(fixtureDir(fw), 'rules.manifest.json'), `${JSON.stringify(sorted, null, 2)}\n`)
}

/**
 * camelCase import identifier for a rule id: "server-use-cache-directive" becomes
 * "serverUseCacheDirective". An identifier that would start with a digit gets a "_" prefix.
 */
export function identFor(id) {
  if (!/^[A-Za-z0-9-]+$/.test(id)) throw new Error(`rule id "${id}" has characters outside [A-Za-z0-9-]`)
  const ident = id
    .split('-')
    .filter(Boolean)
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join('')
  if (!ident) throw new Error(`rule id "${id}" has no letters or digits`)
  return /^\d/.test(ident) ? `_${ident}` : ident
}

/** Source of src/rules/index.ts for entries [{ id, ident }] already sorted by id. */
export function rulesIndexSource(entries) {
  const header = '// GENERATED by scripts/sync-examples.mjs — do not edit'
  const imports = entries.map(({ id, ident }) => `import * as ${ident} from './${id}'`)
  const exported =
    entries.length === 0
      ? 'export const rules = {} as const'
      : ['export const rules = {', ...entries.map(({ id, ident }) => `  '${id}': ${ident},`), '} as const'].join('\n')
  return [header, ...imports, '', exported, ''].join('\n')
}

/**
 * Regenerates fixtures/<fw>/src/rules/index.ts from the manifest. Includes each entry
 * whose stub exists and warns on stderr for the rest. Writes only if the content changes.
 * Returns the rule ids included.
 */
export async function writeRulesIndex(fw) {
  const manifest = await readManifest(fw)
  const entries = []
  const idents = new Map()
  for (const id of Object.keys(manifest).sort()) {
    if (!(await exists(stubPath(fw, id)))) {
      log(`warn ${fw}: rules index skips ${id}, no src/rules/${id}.tsx`)
      continue
    }
    const ident = identFor(id)
    if (idents.has(ident)) {
      throw new Error(`${fw}: rule ids ${idents.get(ident)} and ${id} both map to identifier "${ident}"`)
    }
    idents.set(ident, id)
    entries.push({ id, ident })
  }
  const source = rulesIndexSource(entries)
  const path = rulesIndexPath(fw)
  const current = (await exists(path)) ? await readFile(path, 'utf8') : null
  if (current !== source) await writeFile(path, source)
  return entries.map(({ id }) => id)
}
